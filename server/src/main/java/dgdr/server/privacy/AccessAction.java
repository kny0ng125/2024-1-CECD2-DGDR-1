package dgdr.server.privacy;

/**
 * 접속기록에 남길 행위 유형.
 *
 * <p>「개인정보의 안전성 확보조치 기준」은 접속기록에 처리한 정보주체 정보와
 * 수행업무를 남기도록 한다. 개인정보를 실제로 열람·변경하는 경로만 기록하며,
 * 개인정보가 포함되지 않는 조회(예: 병원 병상 현황)는 대상이 아니다.
 */
public enum AccessAction {

    /** 통화 목록 조회. 날짜 범위로 본인 담당 통화를 나열. */
    VIEW_CALL_LIST,

    /** 특정 통화의 전사 기록 열람. 민감정보 접근. */
    VIEW_CALL_RECORD,

    /** 통화 전사 실시간 구독(SSE). */
    STREAM_CALL_RECORD,

    /**
     * AI 매뉴얼 조회. 전사본을 <b>외부 추론 서버로 전송</b>한다.
     *
     * <p>열람과 구분해 두는 이유: 이것은 조회가 아니라 제3자 제공에 가깝다.
     * 사후에 "누구의 신고 내용이 언제 시스템 밖으로 나갔는가"를 재구성하려면
     * 단순 열람 기록과 섞여 있으면 안 된다.
     */
    QUERY_MANUAL,

    /**
     * 통화 수락. 신고 내용(민감정보) 취득이 시작되는 시점이다.
     *
     * <p>열람이 아니라 수집의 시작이지만 기록 대상으로 둔다. 상황실에서
     * "누가 이 신고를 받았는가"는 사후 검증의 출발점이고, 접속기록이
     * 그 답을 가진 유일한 곳이다.
     */
    ANSWER_CALL,

    /** 수신 거절. 받지 않은 신고도 누가 거절했는지 남아야 한다. */
    REJECT_CALL,

    /** 요원에 의한 통화 종료. */
    HANGUP_CALL,

    /** 보존기간 만료에 따른 파기. */
    PURGE_EXPIRED,

    /** 로그인 성공. */
    LOGIN_SUCCESS,

    /** 로그인 실패. 계정 도용 시도 탐지에 쓰인다. */
    LOGIN_FAILURE
}
